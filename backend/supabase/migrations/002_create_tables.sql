-- 002_create_tables.sql
-- CREACIÓN DE LAS 38 TABLAS
-- ==========================================

CREATE SCHEMA IF NOT EXISTS algoritmos;

-- ==========================================
-- PARTE 1: TABLAS BASE
-- ==========================================

CREATE TABLE algoritmos.roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR NOT NULL,
    name VARCHAR NOT NULL
);

CREATE TABLE algoritmos.users (
    user_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR NOT NULL,
    email VARCHAR NOT NULL,
    password_hash TEXT,
    auth_provider VARCHAR NOT NULL DEFAULT 'local',
    external_id TEXT,
    display_name VARCHAR NOT NULL,
    gender VARCHAR,
    account_status VARCHAR NOT NULL DEFAULT 'activo',
    is_trial BOOLEAN NOT NULL DEFAULT FALSE,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.user_roles (
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    role_id SMALLINT NOT NULL REFERENCES algoritmos.roles(role_id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE algoritmos.careers (
    career_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR NOT NULL,
    name VARCHAR NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE algoritmos.courses (
    course_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR NOT NULL,
    name VARCHAR NOT NULL,
    syllabus_version VARCHAR,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE algoritmos.difficulties (
    difficulty_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR NOT NULL,
    name VARCHAR NOT NULL,
    sort_order SMALLINT NOT NULL,
    initial_lives SMALLINT NOT NULL,
    life_damage SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE algoritmos.game_zones (
    zone_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR NOT NULL,
    name VARCHAR NOT NULL,
    zone_order SMALLINT NOT NULL,
    zone_kind VARCHAR NOT NULL DEFAULT 'unidad',
    description TEXT
);

-- ==========================================
-- PARTE 2: CURSOS, UNIDADES Y SECCIONES
-- ==========================================

CREATE TABLE algoritmos.sections (
    section_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    course_id SMALLINT NOT NULL REFERENCES algoritmos.courses(course_id),
    section_code VARCHAR NOT NULL,
    term VARCHAR,
    career_id SMALLINT REFERENCES algoritmos.careers(career_id),
    created_by UUID REFERENCES algoritmos.users(user_id),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.units (
    unit_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id SMALLINT NOT NULL REFERENCES algoritmos.courses(course_id),
    unit_no SMALLINT NOT NULL,
    title VARCHAR NOT NULL,
    learning_outcome TEXT,
    start_week SMALLINT,
    end_week SMALLINT,
    sort_order SMALLINT NOT NULL
);

CREATE TABLE algoritmos.topics (
    topic_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id SMALLINT NOT NULL REFERENCES algoritmos.units(unit_id),
    title VARCHAR NOT NULL,
    description TEXT,
    syllabus_week SMALLINT,
    sort_order SMALLINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE algoritmos.zone_units (
    zone_id SMALLINT NOT NULL REFERENCES algoritmos.game_zones(zone_id),
    unit_id SMALLINT NOT NULL REFERENCES algoritmos.units(unit_id),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (zone_id, unit_id)
);

CREATE TABLE algoritmos.unit_unlock_rules (
    unit_id SMALLINT PRIMARY KEY REFERENCES algoritmos.units(unit_id),
    minimum_score INTEGER NOT NULL DEFAULT 0,
    diagnostic_minimum INTEGER NOT NULL DEFAULT 70,
    allow_diagnostic BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE algoritmos.topic_prerequisites (
    topic_id BIGINT NOT NULL REFERENCES algoritmos.topics(topic_id),
    prerequisite_topic_id BIGINT NOT NULL REFERENCES algoritmos.topics(topic_id),
    PRIMARY KEY (topic_id, prerequisite_topic_id)
);

CREATE TABLE algoritmos.topic_materials (
    material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL REFERENCES algoritmos.topics(topic_id),
    material_type VARCHAR NOT NULL,
    title VARCHAR NOT NULL,
    body TEXT NOT NULL,
    sort_order SMALLINT NOT NULL DEFAULT 1,
    published BOOLEAN NOT NULL DEFAULT FALSE
);

-- ==========================================
-- PARTE 3: PREGUNTAS Y RETOS
-- ==========================================

CREATE TABLE algoritmos.questions (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL REFERENCES algoritmos.topics(topic_id),
    difficulty_id SMALLINT NOT NULL REFERENCES algoritmos.difficulties(difficulty_id),
    question_type VARCHAR NOT NULL,
    label VARCHAR,
    prompt TEXT NOT NULL,
    code_snippet TEXT,
    explanation TEXT,
    expected_answer TEXT,
    evaluation_config JSONB NOT NULL DEFAULT '{}'::jsonb,
    points SMALLINT NOT NULL DEFAULT 10,
    time_limit_seconds SMALLINT,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_by UUID REFERENCES algoritmos.users(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.question_options (
    option_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES algoritmos.questions(question_id),
    option_key VARCHAR NOT NULL,
    option_text TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order SMALLINT NOT NULL
);

CREATE TABLE algoritmos.game_levels (
    level_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id SMALLINT NOT NULL REFERENCES algoritmos.game_zones(zone_id),
    difficulty_id SMALLINT NOT NULL REFERENCES algoritmos.difficulties(difficulty_id),
    level_no SMALLINT NOT NULL,
    title VARCHAR NOT NULL,
    unlock_rule JSONB NOT NULL DEFAULT '{}'::jsonb,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE algoritmos.level_questions (
    level_id BIGINT NOT NULL REFERENCES algoritmos.game_levels(level_id),
    question_id BIGINT NOT NULL REFERENCES algoritmos.questions(question_id),
    sequence_no SMALLINT,
    PRIMARY KEY (level_id, question_id)
);

CREATE TABLE algoritmos.practical_challenges (
    challenge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL REFERENCES algoritmos.topics(topic_id),
    kind VARCHAR NOT NULL DEFAULT 'practico',
    zone_id SMALLINT REFERENCES algoritmos.game_zones(zone_id),
    title VARCHAR NOT NULL,
    context TEXT NOT NULL,
    task_statement TEXT NOT NULL,
    expected_solution TEXT,
    evaluation_config JSONB NOT NULL DEFAULT '{}'::jsonb,
    difficulty_id SMALLINT NOT NULL REFERENCES algoritmos.difficulties(difficulty_id),
    estimated_minutes SMALLINT NOT NULL DEFAULT 5,
    unlock_after_topic_id BIGINT REFERENCES algoritmos.topics(topic_id),
    published BOOLEAN NOT NULL DEFAULT FALSE
);

-- ==========================================
-- PARTE 4: SESIONES E INTENTOS
-- ==========================================

CREATE TABLE algoritmos.game_sessions (
    session_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    zone_id SMALLINT REFERENCES algoritmos.game_zones(zone_id),
    level_id BIGINT REFERENCES algoritmos.game_levels(level_id),
    difficulty_id SMALLINT NOT NULL REFERENCES algoritmos.difficulties(difficulty_id),
    mode VARCHAR NOT NULL DEFAULT 'ruta',
    status VARCHAR NOT NULL DEFAULT 'en_curso',
    score INTEGER NOT NULL DEFAULT 0,
    lives_remaining SMALLINT,
    current_unit_id SMALLINT REFERENCES algoritmos.units(unit_id),
    current_topic_id BIGINT REFERENCES algoritmos.topics(topic_id),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at TIMESTAMPTZ,
    elapsed_seconds INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE algoritmos.answer_attempts (
    answer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES algoritmos.game_sessions(session_id),
    question_id BIGINT NOT NULL REFERENCES algoritmos.questions(question_id),
    selected_option_id BIGINT REFERENCES algoritmos.question_options(option_id),
    answer_text TEXT,
    is_correct BOOLEAN NOT NULL,
    response_seconds NUMERIC NOT NULL DEFAULT 0,
    points_awarded INTEGER NOT NULL DEFAULT 0,
    answered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    attempt_no SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE algoritmos.challenge_attempts (
    attempt_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    challenge_id BIGINT NOT NULL REFERENCES algoritmos.practical_challenges(challenge_id),
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    session_id UUID REFERENCES algoritmos.game_sessions(session_id),
    submitted_answer TEXT,
    is_correct BOOLEAN,
    points_awarded SMALLINT NOT NULL DEFAULT 0,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_at TIMESTAMPTZ
);

-- ==========================================
-- PARTE 5: PROGRESO DEL JUGADOR
-- ==========================================

CREATE TABLE algoritmos.player_topic_progress (
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    topic_id BIGINT NOT NULL REFERENCES algoritmos.topics(topic_id),
    state VARCHAR NOT NULL DEFAULT 'bloqueado',
    best_score INTEGER NOT NULL DEFAULT 0,
    attempts_count INTEGER NOT NULL DEFAULT 0,
    errors_count INTEGER NOT NULL DEFAULT 0,
    unlocked_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, topic_id)
);

CREATE TABLE algoritmos.player_unit_progress (
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    unit_id SMALLINT NOT NULL REFERENCES algoritmos.units(unit_id),
    state VARCHAR NOT NULL DEFAULT 'bloqueado',
    best_score INTEGER NOT NULL DEFAULT 0,
    unlocked_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, unit_id)
);

CREATE TABLE algoritmos.player_topic_stats (
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    topic TEXT NOT NULL,
    ok INTEGER NOT NULL DEFAULT 0,
    mal INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, topic)
);

-- ==========================================
-- PARTE 6: ACTIVIDAD Y RESULTADOS
-- ==========================================

CREATE TABLE algoritmos.activity_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    event_type VARCHAR NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE algoritmos.player_results (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    zone TEXT NOT NULL,
    difficulty TEXT NOT NULL,
    score INTEGER NOT NULL,
    won BOOLEAN NOT NULL,
    played_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.player_state (
    user_id UUID PRIMARY KEY REFERENCES algoritmos.users(user_id),
    avatar JSONB,
    unlocked_zones TEXT[] NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.player_avatar (
    user_id UUID PRIMARY KEY REFERENCES algoritmos.users(user_id),
    avatar_config JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.checkpoints (
    checkpoint_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    session_id UUID REFERENCES algoritmos.game_sessions(session_id),
    unit_id SMALLINT REFERENCES algoritmos.units(unit_id),
    topic_id BIGINT REFERENCES algoritmos.topics(topic_id),
    level_id BIGINT REFERENCES algoritmos.game_levels(level_id),
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    score INTEGER NOT NULL DEFAULT 0,
    lives_remaining SMALLINT,
    saved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_resumable BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE algoritmos.diagnostic_attempts (
    diagnostic_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    unit_id SMALLINT NOT NULL REFERENCES algoritmos.units(unit_id),
    difficulty_id SMALLINT NOT NULL REFERENCES algoritmos.difficulties(difficulty_id),
    score INTEGER NOT NULL DEFAULT 0,
    passed BOOLEAN NOT NULL DEFAULT FALSE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ
);

-- ==========================================
-- PARTE 7: MATRÍCULAS Y DOCENTES
-- ==========================================

CREATE TABLE algoritmos.enrollments (
    enrollment_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    course_id SMALLINT NOT NULL REFERENCES algoritmos.courses(course_id),
    career_id SMALLINT REFERENCES algoritmos.careers(career_id),
    section_id UUID REFERENCES algoritmos.sections(section_id),
    enrollment_type VARCHAR NOT NULL DEFAULT 'regular',
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE algoritmos.section_teachers (
    section_id UUID NOT NULL REFERENCES algoritmos.sections(section_id),
    teacher_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    PRIMARY KEY (section_id, teacher_id)
);

CREATE TABLE algoritmos.section_invites (
    invite_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    section_id UUID NOT NULL REFERENCES algoritmos.sections(section_id),
    code VARCHAR NOT NULL,
    created_by UUID REFERENCES algoritmos.users(user_id),
    expires_at TIMESTAMPTZ,
    max_uses INTEGER,
    uses_count INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.role_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES algoritmos.users(user_id),
    requested_role VARCHAR NOT NULL DEFAULT 'docente',
    career_id SMALLINT REFERENCES algoritmos.careers(career_id),
    status VARCHAR NOT NULL DEFAULT 'pendiente',
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_by UUID REFERENCES algoritmos.users(user_id),
    reviewed_at TIMESTAMPTZ
);

-- ==========================================
-- PARTE 8: MOTIVOS DE SALIDA Y COMENTARIOS
-- ==========================================

CREATE TABLE algoritmos.exit_reasons (
    reason_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR NOT NULL,
    label VARCHAR NOT NULL
);

CREATE TABLE algoritmos.session_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES algoritmos.game_sessions(session_id),
    reason_id SMALLINT REFERENCES algoritmos.exit_reasons(reason_id),
    comment TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE algoritmos.student_removals (
    removal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR NOT NULL,
    section_id UUID REFERENCES algoritmos.sections(section_id),
    removed_by UUID REFERENCES algoritmos.users(user_id),
    removed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);