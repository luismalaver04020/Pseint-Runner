CREATE OR REPLACE FUNCTION algoritmos.sincronizar_pregunta_con_niveles()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'algoritmos', 'public', 'extensions'
AS $function$
BEGIN
    DELETE FROM level_questions lq
    USING game_levels gl
    WHERE lq.level_id = gl.level_id
      AND lq.question_id = NEW.question_id
      AND (NOT NEW.published OR gl.difficulty_id <> NEW.difficulty_id
           OR NOT EXISTS (
               SELECT 1 FROM topics t JOIN zone_units zu USING (unit_id)
               WHERE t.topic_id = NEW.topic_id AND zu.zone_id = gl.zone_id
           ));

    IF NEW.published THEN
        INSERT INTO level_questions (level_id, question_id, sequence_no)
        SELECT gl.level_id, NEW.question_id,
               (SELECT count(*) + 1 FROM level_questions existing WHERE existing.level_id = gl.level_id)::smallint
        FROM game_levels gl
        JOIN topics t ON t.topic_id = NEW.topic_id
        JOIN zone_units zu ON zu.unit_id = t.unit_id AND zu.zone_id = gl.zone_id
        WHERE gl.difficulty_id = NEW.difficulty_id AND gl.active
        ON CONFLICT (level_id, question_id) DO NOTHING;
    END IF;
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_sincronizar_pregunta_con_niveles ON questions;
CREATE TRIGGER trg_sincronizar_pregunta_con_niveles
AFTER INSERT OR UPDATE OF topic_id, difficulty_id, published ON questions
FOR EACH ROW EXECUTE FUNCTION algoritmos.sincronizar_pregunta_con_niveles();

