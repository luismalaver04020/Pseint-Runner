CREATE OR REPLACE FUNCTION algoritmos.api_recuperar_checkpoint(p_zone_code text, p_difficulty_code text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'algoritmos', 'public', 'extensions'
AS $function$
DECLARE v_user_id uuid := auth.uid(); v_checkpoint jsonb;
BEGIN
    IF v_user_id IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesión'; END IF;
    SELECT jsonb_build_object(
        'session_id', gs.session_id,
        'score', cp.score,
