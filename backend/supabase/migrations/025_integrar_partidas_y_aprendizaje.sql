-- Vincula la partida al primer nivel configurado con preguntas publicadas.
-- Si no hay niveles configurados, la partida conserva el flujo actual por zona.
CREATE OR REPLACE FUNCTION algoritmos.api_asignar_nivel_partida(p_session_id uuid)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'algoritmos', 'public', 'extensions'
AS $function$
DECLARE v_user_id uuid := auth.uid(); v_level_id bigint;
BEGIN
    IF v_user_id IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesión'; END IF;
