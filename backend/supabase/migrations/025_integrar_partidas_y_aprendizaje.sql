-- Historial de intentos: los aciertos de opción múltiple se derivan de la
-- opción guardada en BD; los resultados de código llegan del evaluador backend.
CREATE OR REPLACE FUNCTION algoritmos.api_registrar_intento_juego(
    p_session_id uuid,
    p_question_id bigint,
    p_correcto boolean,
    p_option_id bigint DEFAULT NULL,
    p_option_key text DEFAULT NULL,
    p_respuesta text DEFAULT NULL,
    p_segundos numeric DEFAULT 0,
    p_puntos integer DEFAULT 0
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'algoritmos', 'public', 'extensions'
AS $function$
DECLARE
    v_user_id uuid := auth.uid();
    v_correcto boolean := COALESCE(p_correcto, false);
    v_tipo text;
    v_answer_id bigint;
BEGIN
    IF v_user_id IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesión'; END IF;
    IF NOT EXISTS (
        SELECT 1 FROM game_sessions
        WHERE session_id = p_session_id AND user_id = v_user_id
    ) THEN RAISE EXCEPTION 'La partida no pertenece a tu cuenta'; END IF;
    IF NOT EXISTS (
        SELECT 1 FROM question_assignments
        WHERE session_id = p_session_id AND user_id = v_user_id AND question_id = p_question_id
    ) THEN RAISE EXCEPTION 'La pregunta no fue asignada a esta partida'; END IF;
    SELECT question_type INTO v_tipo FROM questions WHERE question_id = p_question_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'No se encontró la pregunta'; END IF;
    IF v_tipo = 'codigo' THEN
        RAISE EXCEPTION 'Los intentos de código se guardan desde el evaluador del servidor';
    END IF;
    IF p_option_id IS NOT NULL THEN
        SELECT is_correct INTO v_correcto
        FROM question_options
        WHERE option_id = p_option_id AND question_id = p_question_id;
        IF NOT FOUND THEN RAISE EXCEPTION 'La opción no corresponde a la pregunta'; END IF;
    ELSIF p_option_key IS NOT NULL THEN
        SELECT is_correct INTO v_correcto
        FROM question_options
        WHERE option_key = p_option_key AND question_id = p_question_id;
        IF NOT FOUND THEN RAISE EXCEPTION 'La opción no corresponde a la pregunta'; END IF;
    ELSE
        v_correcto := false;
    END IF;

    INSERT INTO answer_attempts (
        session_id, question_id, selected_option_id, answer_text, is_correct,
        response_seconds, points_awarded
    ) VALUES (
        p_session_id, p_question_id, p_option_id, left(p_respuesta, 12000), v_correcto,
        greatest(0, least(COALESCE(p_segundos, 0), 3600)),
        CASE WHEN v_correcto THEN greatest(0, least(COALESCE(p_puntos, 0), 1000)) ELSE 0 END
    ) RETURNING answer_id INTO v_answer_id;

    INSERT INTO activity_events (user_id, event_type, metadata)
    VALUES (v_user_id, 'respuesta_registrada', jsonb_build_object(
        'session_id', p_session_id, 'question_id', p_question_id,
        'correcta', v_correcto, 'answer_id', v_answer_id
    ));
    RETURN v_answer_id;
END;
$function$;

