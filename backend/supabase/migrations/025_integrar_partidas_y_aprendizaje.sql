CREATE OR REPLACE FUNCTION algoritmos.api_enviar_feedback_partida(
    p_session_id uuid, p_reason_code text, p_comment text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'algoritmos', 'public', 'extensions'
AS $function$
DECLARE v_user_id uuid := auth.uid(); v_reason smallint; v_feedback bigint;
BEGIN
    IF v_user_id IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesión'; END IF;
    IF NOT EXISTS (SELECT 1 FROM game_sessions WHERE session_id = p_session_id AND user_id = v_user_id) THEN
        RAISE EXCEPTION 'La partida no pertenece a tu cuenta';
