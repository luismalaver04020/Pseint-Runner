      AND gs.status = 'en_curso' AND gs.zone_id IS NOT NULL
      AND gz.code = p_zone_code AND d.code = p_difficulty_code
      AND COALESCE(cp.lives_remaining, 0) > 0
    ORDER BY cp.saved_at DESC
    LIMIT 1;
    RETURN v_checkpoint;
END;
$function$;

