-- Guarda un checkpoint resumible sin serializar objetos del Canvas o referencias React.
CREATE OR REPLACE FUNCTION algoritmos.api_guardar_checkpoint_juego(
    p_session_id uuid, p_payload jsonb, p_score integer, p_lives smallint
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'algoritmos', 'public', 'extensions'
AS $function$
DECLARE
    v_user_id uuid := auth.uid();
    v_checkpoint uuid;
    v_session game_sessions%ROWTYPE;
BEGIN
    IF v_user_id IS NULL THEN RAISE EXCEPTION 'Debes iniciar sesión'; END IF;
    SELECT * INTO v_session FROM game_sessions
    WHERE session_id = p_session_id AND user_id = v_user_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'La partida no pertenece a tu cuenta'; END IF;
    IF v_session.status <> 'en_curso' THEN RAISE EXCEPTION 'La partida ya terminó'; END IF;
    IF p_payload IS NULL OR jsonb_typeof(p_payload) <> 'object' OR octet_length(p_payload::text) > 4096 THEN
        RAISE EXCEPTION 'El checkpoint no es válido';
    END IF;

    SELECT checkpoint_id INTO v_checkpoint
    FROM checkpoints
    WHERE session_id = p_session_id AND user_id = v_user_id AND is_resumable
    ORDER BY saved_at DESC
    LIMIT 1;

    UPDATE checkpoints SET is_resumable = false
    WHERE session_id = p_session_id AND user_id = v_user_id AND is_resumable
      AND checkpoint_id <> COALESCE(v_checkpoint, '00000000-0000-0000-0000-000000000000'::uuid);

    IF v_checkpoint IS NULL THEN
        INSERT INTO checkpoints (user_id, session_id, unit_id, topic_id, level_id,
                                 payload, score, lives_remaining, is_resumable)
        VALUES (v_user_id, p_session_id, v_session.current_unit_id, v_session.current_topic_id,
                v_session.level_id, p_payload, greatest(0, COALESCE(p_score, 0)),
                greatest(0, COALESCE(p_lives, 0)), true)
        RETURNING checkpoint_id INTO v_checkpoint;
    ELSE
        UPDATE checkpoints SET
            unit_id = v_session.current_unit_id,
            topic_id = v_session.current_topic_id,
            level_id = v_session.level_id,
            payload = p_payload,
            score = greatest(0, COALESCE(p_score, 0)),
            lives_remaining = greatest(0, COALESCE(p_lives, 0)),
            saved_at = now(),
            is_resumable = true
        WHERE checkpoint_id = v_checkpoint;
    END IF;
    RETURN v_checkpoint;
END;
$function$;

